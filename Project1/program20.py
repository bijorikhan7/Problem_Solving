
#List
# using list (in , not , add items ,multiple items)

subjects = ["bangla","english","math","physics","chemistry","biology"]
print(subjects)
print(subjects[0])
print(subjects[3:])
print(subjects[2:5])
print(subjects[-1])

#in/ not in
print("biology" in subjects)
print("ict" not in subjects)

#add
print(subjects + ["ict" , 34 , "computer"])

#multiple
print(subjects * 3)






